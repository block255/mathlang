// 数语引擎 · **删空一段之后：收掉它自己的那个换行**（2026-11-10，反馈 ③）
//
// ============================ 为什么单开一个文件 ============================
// 这条判据原来只写在逐字删除那一条路上（`render/math_nav.dart` 的
// `_visibleObjectDelete → _normalizeEmptyParagraph`）。于是同一个意图，
// 退格删光一行 ⇒ 收掉了换行；**拖选整行删除 / 剪切** ⇒ 没走这段逻辑 ⇒ 多出整整一行空白：
//
//   逐字：`A⏎⏎B⏎⏎C` 删光 B ⇒ `A⏎⏎⏎C`（2 个空行 = 版面 1 行）✅
//   选区：同一个意图       ⇒ `A⏎⏎⏎⏎C`（3 个空行 = 版面 2 行）❌ 用户实测"空出两个空行"
//
// 口径（2026-11-10 用户拍板，写进《行与段-空行基准》）：
//   **删掉一段的可见内容后，上下文距离不变** —— 被删空的位置算 1 行，
//   两侧原来各有几行就还是几行。实现 = 收掉并置出来的那一个换行。
//
// ★ 这条是**字节级改写**（把 `A⏎⏎⏎⏎C` 写成 `A⏎⏎⏎C`），**不是渲染层的修正**；
//   渲染层那条（`blank_runs.extraBlankHeight(n) = (n-1) × 行高`："两段之间第一个空行是
//   段落分隔符、零高度"）是另一层，两层都要在，缺一层就会多出一行。

/// 删除 `[from, to)` 之后，要不要顺手把一个换行也收掉。
///
/// 返回：`(at: 那个换行的下标, atEnd: 它所在的换行串是否一直延伸到文末)`；不收 ⇒ null。
///
/// 四条判据（缺一不可）：
///   ① **区间里不含换行** —— 跨行选区删的是"若干行"，不是"删空一段"，**不许收**
///      （否则 `A⏎⏎B⏎⏎C` 里选 `B⏎` 会被多收一格，变成 `A⏎⏎C`）；
///   ② 区间左端是**行首**、右端是**行末**（`src[to] == '\n'`）—— 这一行的可见内容被整个删光；
///      还剩字（**包括只剩空格**）就不算删空 ⇒
///      2026-11-10 用户拍板"有空格的不算完全空行"（旧判据用 `trim()`，会把只剩空格的行也收掉）；
///   ③ 那个换行所在的一串换行长度 **≥ 2** —— 单个换行是段内软换行，收它等于删结构；
///   ④ 只回答"收哪一格"，**光标与撤销由调用方决定**（两条通道的光标规则不同）。
///
/// 判据本体的旧版本在 `render/math_nav.dart:998`（注释里带着 2026-10-28 的两次手测结论）。
({int at, bool atEnd})? emptiedLineCollapse(String src, int from, int to) {
  if (from < 0 || to > src.length || to <= from) return null;
  // ① 跨行 ⇒ 不归这条管
  if (src.substring(from, to).contains('\n')) return null;
  // ② 左端行首、右端行末
  if (from != 0 && src[from - 1] != '\n') return null;
  if (to >= src.length || src[to] != '\n') return null;
  // ③ 换行串长度（把要收的那一格算进去）
  int a = from - 1;
  while (a >= 0 && src[a] == '\n') {
    a--;
  }
  int b = to + 1;
  while (b < src.length && src[b] == '\n') {
    b++;
  }
  final int run = (from - 1 - a) + 1 + (b - to - 1);
  if (run < 2) return null;
  return (at: to, atEnd: b >= src.length);
}
