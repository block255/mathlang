// 数语引擎 · **数学段里的语法字符转义**（2026-11-01，反馈 6 / 11 · R8）
//
// 病灶（用户实测）：
//   · 光标在行间公式里，想把中括号打成花括号 ⇒ 打出 `{` ⇒ tex 花括号不配平
//     ⇒ 整块 `[公式不完整]`；
//   · 想打 `^`（Shift+6）打成 Shift+7 ⇒ 打进一个 `&` ⇒ TeX 报
//     `Misplaced alignment tab character &` ⇒ 同样不完整。
//
// 口径（原则 2「用户永远不需要看数学编码」+ 平权）：用户按的是键盘上一个**普通字符**，
//   不许因为"它碰巧是 TeX 的语法字符"就把文档弄坏。
//   ⇒ 数学段里**单字符**输入这些字符时，存成**转义形式**（`\{` `\}` `\&` `\%` `\#`），
//     渲染出来仍是用户按的那个字符（视觉完全一致），tex 却是合法的。
//
// ★ 三条边界（都别越）：
//   ① **只对单字符输入生效**（`text.length == 1`）—— 粘贴多行 LaTeX 是"用户就是要这段源码"，
//      转义会把 `\begin{cases}` 之类的真语法毁掉；
//   ② **只在数学段里**生效 —— 正文里 `{` `}` `&` 本来就是普通字符；
//   ③ `$` **不转义**：它是"新建/续写公式"的入口（`insert_guard` 里明写着不许拦）。
//      `^` / `_` 也不在这里处理 —— 它们有专门的两条路（自动展开 / 结构插入）。

/// 数学段里的一次**单字符**输入要不要转义成字面字符。
///
/// [inMath] = 光标是否在数学段（行内 `$…$` 或行间 `$$…$$`）里。
/// 返回要真正写进缓冲区的文本（不需要转义时原样返回）。
String escapeMathSyntax(String text, {required bool inMath}) {
  if (!inMath || text.length != 1) return text;
  switch (text) {
    case '{':
      return r'\{';
    case '}':
      return r'\}';
    case '&':
      return r'\&';
    case '%':
      return r'\%';
    case '#':
      return r'\#';
  }
  return text;
}
