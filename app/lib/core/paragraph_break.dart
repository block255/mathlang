// 数语引擎 · **段落分隔符**（2026-10-28，用户拍板"段间距不承接字符"）
//
// 为什么单开一个文件：这是**一条纯文本判据**（`core` 层），
//   · `editor/blank_runs.dart` 用它算"哪一个空行是分隔符"；
//   · `render/math_nav.dart` 用它在 `←`/`→` 上跳过它。
// 放在 `core` 才不会让 `render` 反过来依赖 `editor`（分层方向见 `CONTRIBUTING`）。
//
// ## 它是什么
//
// Markdown 里一段的结束是**两个**换行符：第一个终止最后一行（行终止符），
// 第二个才是**段落分隔符** —— 它不终止任何一行。于是：
//
//   · **行数** = `\n` 数 + 1（最后那个空串是"常驻行"，即 EOF 那一格）；
//   · **段与段之间恒有恰好 1 个零高度的"行"** = 这个分隔符所占的那一格，
//     它在缓冲区里是个真实偏移（`\n` 与 `\n` 之间），**但在版面上没有高度**。
//
// ## 为什么它不能承接光标
//
// 光标必须画在一个**行盒**里（行顶 + 行内内缩）。分隔符没有行盒 ⇒ 只能画进段距里，
// 两种后果都不可接受（2026-10-28 实测）：
//   ① 那个 y 精确等于"**上一段的段内下一行**"（`行盒 + 3.6`），比下一段高 11.2（= 段距）
//      ⇒ 光标悬在两行之间的缝里、压着下一行，用户："段间距竟然能当一个容器行"；
//   ② 在那儿打字 = 填掉段落边界 ⇒ **两段被并成一段**（数据级损坏）。
//
// ⇒ 结论：**它不是位置**。所有"产生光标"的路径（编辑 / 点击 / 方向键）都不许产生它。

/// [o] 是不是**段落分隔符**那一格（**不是位置**）。
///
/// 判据（只看缓冲区，不需要块模型）：
///   · 它是换行符，且**紧跟在上一行的换行符后面**（`\n\n` 里的第二个）；
///   · 它是这一串换行的**第一个**（`甲⏎⏎⏎乙` 里只有第一个是分隔符，第二个是真行）；
///   · 前面**有内容**（文首空行不是分隔符）、后面**有内容**（文末空行也不是 ——
///     文末没有"下一段"来用掉它，所以文末每个空行都是真行）。
bool isParagraphSeparator(String buf, int o) {
  if (o <= 0 || o >= buf.length) return false;
  if (buf[o] != '\n' || buf[o - 1] != '\n') return false;
  if (o >= 2 && buf[o - 2] == '\n') return false;
  var back = o - 2;
  while (back >= 0 && buf[back] == '\n') {
    back--;
  }
  if (back < 0) return false; // 文首
  var fwd = o + 1;
  while (fwd < buf.length && buf[fwd] == '\n') {
    fwd++;
  }
  return fwd < buf.length; // 文末 ⇒ 后面没内容 ⇒ 不是分隔符
}

/// 把方向键落点**挪出段落分隔符**（`forward` = `→` 往右、否则 `←` 往左）。
///
/// 为什么不在分隔符上画一根：它没有行盒（见文件头）。既然不是位置，就**不停在它上面** ——
/// `→` 从上一行行末一步到下一段行首，`←` 从下一段行首一步回上一行行末。
int skipParagraphSeparator(String buf, int o, {required bool forward}) {
  var x = o;
  while (x > 0 && x < buf.length && isParagraphSeparator(buf, x)) {
    x += forward ? 1 : -1;
  }
  return x;
}
