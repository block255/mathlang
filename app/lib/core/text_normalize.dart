// 数语引擎 · **换行归一**（2026-10-23 公测反馈，批 2）
//
// 为什么需要：外部文件（AI 答案 / 记事本 / 别的编辑器）普遍是 **CRLF**，
// 而本项目的"整行语法"（`$$` 围栏、`---` 分隔线、`# ` 标题、列表标记、分页符）都按**行**判定。
// 行尾多出来的 `\r` 会让这些判据**静默失效** —— 实测用户那份 DeepSeek 抄写稿
// （`CR=140 / LF=140`）里 3 个 `---` 分隔线**一个都没认出来**，页面上原样印成 `---`。
//
// 归一放在**进门处**（`DocBuffer.loadDocument` / 粘贴载荷），而不是在渲染层逐处 trim ——
// 否则 `\r` 会留在缓冲区里，白占偏移、污染字符数与光标（还会跟着导出/复制跑出去）。
//
// **纯 Dart**：没有 Flutter 依赖。

/// 把 CRLF / 单独的 CR 统一成 LF。已经是 LF 的文本**原样返回同一个实例**。
String normalizeNewlines(String s) {
  if (!s.contains('\r')) return s;
  return s.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
}
