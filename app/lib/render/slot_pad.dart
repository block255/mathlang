// 数语引擎 · **空槽占位垫**（④-1 虚线框自绘 ＋ ④-2 空槽加宽 —— 两者共用的唯一事实来源）
//
// 规格：《位点与结构导航》**§6.1** —— 空槽 = 1px 虚线 `#B0BEC5`；当前槽 = 实线 ＋ 淡蓝底 `#E3F2FD`。
// 落地方式：**注入一个看不见的"垫子"占住版面** ＋ **自绘层**画框（引擎画不出虚线）。
//
// ─────────────────────────────────────────────────────────────
// ★★ 探针数据（2026-10-16，`_cache\probe_slot_pad{,2,3}.log`；字号 16，**text 样式 = 行内**）
//
// | 做法 | 看不见？ | 行内槽宽 | 行内空分式 | 配对账 |
// |---|---|---|---|---|
// | 现状 `\textcolor{#B0BEC5}{\square}` | ✗ 看得见灰方块 | 11.2 | 15.0×19.4 | 1 盒/1 原子 ✓ |
// | `\phantom{\square}` | ✓（`Opacity(0)`） | 11.2 | 15.0×19.4 | **内层字形盒还在 ⇒ 多 1 盒** ✗ |
// | `\vphantom{\square}` ＋ 零高 rule | ✓ | 11.2 | 15.0×19.4 | 字形盒**溢出到左边**（实测 x −6.1）✗ |
// | 零高 `\rule{1.2em}{0pt}` 单独用 | ✓ | 19.2 | **塌成 21.8 高** ✗ | 多 1 盒 ✗ |
// | 白 `\rule{1.2em}{18mu}` | ✓ | 22.5 | **撑高到 29.5**（+10px）✗ | 0 原子 ⇒ 要补账 |
// | ★ **白 `\square` ＋ 零高白 `\rule{0.3em}{0pt}`** | ✓ | **16.8** | **19.4（与 □ 逐像素相同）** | 多 1 盒 ⇒ 补 1 原子 |
//
// ⇒ 取最后一行。理由：**字形垫保证"高度 / 基线 / 行内排版完全不变"** ——
//   这一条是硬的：白 `\rule` 那一版会把空分式**撑高 ~10 px**，等于"换槽时版面跳"；
//   而**零高宽度垫只补宽**，把行内槽从 11.2 补到 **16.8 ≥ 一个正文汉字（16.0）**（§6.1 的触摸目标）。
//   ★ 宽度用 `em`（不是 pt）：它是"正文的字"的度量、随正文号缩放，且**不随层级缩小**
//     （引擎的 `em` 取 `atLeastText()` 的倍率）—— 所以行内（script 层）也够宽。
//
// ★★ 代价（诚实记账）：它**多 1 个叶盒 / 0 个原子** ⇒ 必须在词法侧补 **1 个合成原子**
//    （`visible_atoms.dart` 认 [kSlotPadFiller]；与 §11.18 尾垫**同一个机制**）。
//    少补一个就"叶盒数 ≠ 原子数" ⇒ `hitTestMathTex` **静默返回 null** ⇒ 公式内点击全废
//    —— 这个坑本仓踩过四次，所以这里把"账"写在最前面。
//
// ★ 白墨的已知代价（接受）：垫子的"墨"是**纸色**。① 页面不是纯白时（未来的深色模式）会露出来；
//   ② 未来的选区高亮若画在数学**之下**，会在垫子处露出一个白块。⇒ M2 做选区时**必须复核这一条**。
//   （当前槽的垫子是淡蓝 `#E3F2FD`，而自绘层还会在上面盖一层同色底 ⇒ 两种情形都不会露。）
//
// **纯 Dart（无 Flutter 依赖）。**

/// 垫子里的字形 —— 自绘层靠"它 ＋ 紧邻的宽度垫"认出"这是我们注入的垫子"（见 `math_caret.scanSlotPads`）。
///
/// ★★ **为什么要挑字形**（2026-10-17 真实字体下探针实测，字号 20）：
/// | 字形 | ¶ 盒 | 说明 |
/// |---|---|---|
/// | `\square` / `\blacksquare` / `\Box` | 15.6 × **31**（1.55em） | ✗ 盒高落在 **AMS/回退字体**的度量上 ⇒ 框必然"偏大、顶穿分数线"（用户实测） |
/// | `x` | 11.4 × 21 | ✓ 数学字体度量（1.05em），但偏窄 |
/// | **`M`** | **19.4 × 21** | ✓ 数学字体度量 **且宽**（≈0.97em，帮 ④-2 够到"一个正文汉字"） |
/// | `.` `\cdot` `\ast` `\prime` | 5.6 × **25** | ✗ 度量怪（1.25em） |
///
/// ⇒ 取 `M`：**不可见**（白墨）、¶ 盒 = **数学字体自己的行盒**、宽度还比 □ 更够
/// （实测行内空分式：`\square` 版 12.6 → `M` 版 21.5，≥ 一个正文汉字 16.0 ✓）。
const String kSlotPadGlyph = 'M';

/// 零高**宽度垫**：`0.3em` 在字号 16 下行内 ≈ 5.6 px，刚好把 11.2 的字形垫补到 ≥ 16。
const String kSlotPadFiller = r'\rule{0.3em}{0pt}';

/// 垫子本体（字形 ＋ 宽度垫）。**顺序不能反**：字形在前、宽度垫紧接其右。
const String kSlotPadInner = '$kSlotPadGlyph$kSlotPadFiller';

/// **空槽**的垫子（白墨 ⇒ 看不见；框由自绘层画虚线）
const String kSlotPadTex = '\\textcolor{#FFFFFF}{$kSlotPadInner}';

/// **当前槽**的垫子。
///
/// ★★ 2026-10-18 改：墨色也**不可见**了。原先用淡蓝 `#E3F2FD` 当墨，
///   在纯白纸面上会露出一个淡蓝的 `M` 字形（用户实测："随光标闪烁若隐若现的 M 图标"）。
///   "光标在哪一格"改由**自绘层**画淡蓝底 + 虚线框（它本来就不占版面）。
///   与空槽的区别只剩**一个色阶**（`#FEFEFE` vs `#FFFFFF`）：两者肉眼都看不见，
///   但字符串不同 ⇒ 注入链与测试仍能分别定位两种垫子，也不会互相当子串重复计数。
const String kSlotPadCurrentTex = '\\textcolor{#FEFEFE}{$kSlotPadInner}';

// ---------------------------------------------------------------------------
// ★★ 结构尾垫（2026-10-15，设计稿 §11.18）—— 与上面两个垫子**同一个机制**，故同住一处
// ---------------------------------------------------------------------------

/// **包裹型结构**的内容末尾塞一段"看不见但占宽"的横线，让它的**装饰跟着内容一起变长**。
///
/// 解决的是用户实测的那个"点不准"：
/// `\sqrt{2}` 的横线**不超出**被开方数 ⇒ 结构右缘 **==** 内容右缘 ⇒
/// "里面式子末尾"与"根号整体末尾"**落在同一根像素上**，光标也长得一模一样
/// （分式不同：分数线两头**超出**分子分母，所以它天然有"结构专属像素"）。
///
/// 加了尾垫之后：
/// · **视觉**：横线比内容长一截 ⇒ 两根像素分开（内容末尾在 `2` 右缘、结构末尾在横线末端）
/// · **点击**：尾垫之内（横线之下）→ 内容末尾；越过横线末端（公式盒右缘之外）→ 结构末尾
///
/// ★ **宽度必须用绝对单位**（`pt`）：`em` 会随字号缩小，小字号下会被
///   `leaf_boxes.kMinLeafWidth = 2.0` **过滤掉** ⇒ 叶盒数 ≠ 原子数 ⇒
///   `hitTestMathTex` **静默返回 null**（公式内点击全废）—— 这个坑踩过四次。
/// ★ 它**会多出一个叶盒** ⇒ 词法侧必须为它产出一个**原子**（`visible_atoms.dart` 认它，
///   **在走查顺序里**产出 —— 不能事后按源偏移排序，见那条注释）。
/// ★ 宽度取 `3pt`（≈ 4 px，2026-10-15 用户看图后定的 —— `6pt` 那版"多了一点点"）。
///   ⚠️ **下限**：不能再小于 `leaf_boxes.kMinLeafWidth = 2.0`，否则叶盒被过滤 ⇒
///   叶盒数 ≠ 原子数 ⇒ 命中**静默返回 null**（上面那条坑）。
/// ★★ **高度必须是 0，这是刻意的**：`leaf_boxes` 的"细线装饰"判据是
///   **严格正的极小高度**（`0 < h < 2`，用来摘掉 `\overline` 的 0.6 px 横线），
///   所以零高的尾垫**照样是有效叶盒** ✓ —— 它必须留下，因为它是"结构末尾"的点击区。
///   ⚠️ 别把它"顺手改成非零高"（如 `\rule{3pt}{8pt}`）：那是**看得见的黑块**。
const String kStructTailTex = r'\rule{3pt}{0pt}';

/// ★★ 2026-10-18 晚（用户的设计判断："**一开始就按占位框的宽度来排**"）：
/// 多行环境里**空格子**恒定占的宽度（零高 `rule`，只看宽）。
///
/// 为什么要有它：环境格子的"占位框"以前靠临时注入垫子撑宽 ⇒ 光标换一格，那一列就变宽
/// （列间距不均、行列式竖线跟着变）；完全撤掉又变成"框没地方画、贴着别的内容"。
/// 正解是**排版时就预留**这块宽度：不管光标在不在、画不画框，列宽恒定 ⇒ 排版一个像素都不动。
/// ★ 零高：不影响行高与对齐；★ 用 `em`：随正文号缩放。
const String kEnvCellFillTex = r'\rule{0.6em}{0pt}';