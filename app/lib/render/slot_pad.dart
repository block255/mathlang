// 数语引擎 · **空槽占位垫**（④-1 虚线框自绘 ＋ ④-2 空槽加宽 —— 两者共用的唯一事实来源）
//
// 规格：《位点与结构导航》**§6.1** —— 空槽 = 1px 虚线 `#B0BEC5`；当前槽 = 实线 ＋ 淡蓝底 `#E3F2FD`。
// 落地方式：**注入一个看不见的"垫子"占住版面** ＋ **自绘层**画框（引擎画不出虚线）。
//
// ─────────────────────────────────────────────────────────────
// ★★ 探针数据（2026-10-16，`_cache\probe_slot_pad{,2,3}.log`；字号 16，**text 样式 = 行内**）
//
// | 做法 | 看不见？ | 行内槽宽 | 行内空分式 | 配对账 |
// |---|---|---|---|---|
// | 现状 `\textcolor{#B0BEC5}{\square}` | ✗ 看得见灰方块 | 11.2 | 15.0×19.4 | 1 盒/1 原子 ✓ |
// | `\phantom{\square}` | ✓（`Opacity(0)`） | 11.2 | 15.0×19.4 | **内层字形盒还在 ⇒ 多 1 盒** ✗ |
// | `\vphantom{\square}` ＋ 零高 rule | ✓ | 11.2 | 15.0×19.4 | 字形盒**溢出到左边**（实测 x −6.1）✗ |
// | 零高 `\rule{1.2em}{0pt}` 单独用 | ✓ | 19.2 | **塌成 21.8 高** ✗ | 多 1 盒 ✗ |
// | 白 `\rule{1.2em}{18mu}` | ✓ | 22.5 | **撑高到 29.5**（+10px）✗ | 0 原子 ⇒ 要补账 |
// | ★ **白 `\square` ＋ 零高白 `\rule{0.3em}{0pt}`** | ✓ | **16.8** | **19.4（与 □ 逐像素相同）** | 多 1 盒 ⇒ 补 1 原子 |
//
// ⇒ 取最后一行。理由：**字形垫保证"高度 / 基线 / 行内排版完全不变"** ——
//   这一条是硬的：白 `\rule` 那一版会把空分式**撑高 ~10 px**，等于"换槽时版面跳"；
//   而**零高宽度垫只补宽**，把行内槽从 11.2 补到 **16.8 ≥ 一个正文汉字（16.0）**（§6.1 的触摸目标）。
//   ★ 宽度用 `em`（不是 pt）：它是"正文的字"的度量、随正文号缩放，且**不随层级缩小**
//     （引擎的 `em` 取 `atLeastText()` 的倍率）—— 所以行内（script 层）也够宽。
//
// ★★ 代价（诚实记账）：它**多 1 个叶盒 / 0 个原子** ⇒ 必须在词法侧补 **1 个合成原子**
//    （`visible_atoms.dart` 认 [kSlotPadFiller]；与 §11.18 尾垫**同一个机制**）。
//    少补一个就"叶盒数 ≠ 原子数" ⇒ `hitTestMathTex` **静默返回 null** ⇒ 公式内点击全废
//    —— 这个坑本仓踩过四次，所以这里把"账"写在最前面。
//
// ★ 白墨的已知代价（接受）：垫子的"墨"是**纸色**。① 页面不是纯白时（未来的深色模式）会露出来；
//   ② 未来的选区高亮若画在数学**之下**，会在垫子处露出一个白块。⇒ M2 做选区时**必须复核这一条**。
//   （当前槽的垫子是淡蓝 `#E3F2FD`，而自绘层还会在上面盖一层同色底 ⇒ 两种情形都不会露。）
//
// **纯 Dart（无 Flutter 依赖）。**

/// 垫子里的字形 —— 自绘层靠"它 ＋ 紧邻的宽度垫"认出"这是我们注入的垫子"（见 `math_caret.scanSlotPads`）。
const String kSlotPadGlyph = '□';

/// 零高**宽度垫**：`0.3em` 在字号 16 下行内 ≈ 5.6 px，刚好把 11.2 的字形垫补到 ≥ 16。
const String kSlotPadFiller = r'\rule{0.3em}{0pt}';

/// 垫子本体（字形 ＋ 宽度垫）。**顺序不能反**：字形在前、宽度垫紧接其右。
const String kSlotPadInner = '\\square$kSlotPadFiller';

/// **空槽**的垫子（白墨 ⇒ 看不见；框由自绘层画虚线）
const String kSlotPadTex = '\\textcolor{#FFFFFF}{$kSlotPadInner}';

/// **当前槽**的垫子（淡蓝墨 ⇒ 即使自绘层缺席，用户仍看得出"光标在哪一格"）
const String kSlotPadCurrentTex = '\\textcolor{#E3F2FD}{$kSlotPadInner}';
